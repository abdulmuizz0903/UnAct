"""Generate every LaTeX table of the results section directly from results/*.csv.

Run `python paper/make_tables.py`; the .tex files land in paper/tables/ and are
meant to be \\input{} rather than pasted, so a re-run of an experiment updates the
paper. Requires booktabs and multirow.

tables/numbers.tex defines one macro per number quoted in the prose
(e.g. \\numDeltaUnActCten), so the text never contains a hand-copied number.

Main body : tab_main, tab_vit
Appendix  : tab_main_full, tab_data_efficiency, tab_cost, tab_multiclass,
            tab_sequential,
            tab_e11, tab_vit_variants, tab_relearn, tab_sensitivity,
            tab_selectivity, tab_ssd_grid, tab_lfssd_grid, tab_unact_grid
"""
