def _worst_one_step(grid, axes, selected):
    q = dict(zip(axes, selected))
    mask = np.ones(len(grid), bool)
    for a, v in q.items():
        mask &= (grid[a] == v).values
    base = grid[mask].score.iloc[0]
    worst, where = base, None
    for a in axes:
        vals = sorted(grid[a].unique())
        i = vals.index(q[a])
        for j in (i - 1, i + 1):
            if not 0 <= j < len(vals):
                continue
            r = dict(q); r[a] = vals[j]
            m = np.ones(len(grid), bool)
            for k, v in r.items():
                m &= (grid[k] == v).values
            sc = grid[m].score.iloc[0]
            if sc > worst:
                worst, where = sc, (a, vals[j])
    return base, worst, where


