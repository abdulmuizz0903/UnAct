def table_cost():
    c = load_cost_l4()
    src = "cost_breakdown_l4.csv + cost_breakdown_l4_k1.csv + cost_breakdown_l4_k5.csv"
    lines = []
    for ds in DATASETS:
        s = c[c.dataset == ds].sort_values("iters")
        block = []
        for _, r in s.iterrows():
            sel = (r.percentile, r.gamma, int(r.iters)) == UNACT_SELECTED[ds]
            share = 100 * r.ssd_full / r.ssd_cold
            ra, rc = r.ssd_amort / r.unact_s, r.ssd_cold / r.unact_s
            k = int(r.iters)
            tag = "" if not sel else "$^\\dagger$"
            block.append(
                f" & {k}{tag} & \\texttt{{\\scriptsize p{r.percentile:g}, $\\gamma${r.gamma:g}}} & "
                f"{r.score:.2f} & {r.unact_s:.2f} & {r.ssd_amort:.2f} & {r.ssd_cold:.1f} & "
                f"{share:.0f} & {bold_if(ra, ra > 1)}$\\times$ & {rc:.0f}$\\times$ \\\\")
            kw = {1: "Kone", 5: "Kfive", 20: "Ktwenty"}[k]
            num(f"numTimeUnAct{DS_WORD[ds]}{kw}", r.unact_s, src)
            num(f"numTimeSSDAmort{DS_WORD[ds]}{kw}", r.ssd_amort, src)
            num(f"numTimeSSDCold{DS_WORD[ds]}{kw}", r.ssd_cold, src, "{:.1f}")
            num(f"numSpeedupAmort{DS_WORD[ds]}{kw}", ra, src, "{:.1f}")
            num(f"numSpeedupCold{DS_WORD[ds]}{kw}", rc, src, "{:.0f}")
            num(f"numDeltaUnAct{DS_WORD[ds]}{kw}", r.score, src)
            num(f"numFullShare{DS_WORD[ds]}{kw}", share, src, "{:.0f}")
        block[0] = f"\\multirow{{{len(block)}}}{{*}}{{{DATASET_LABEL[ds]}}}" + block[0]
        lines.append("\n".join(block))
    body = r"""\begin{table}[t]
\centering
\caption{Wall-clock cost on one L4, serialised, full forget class (class 3),
warm-up repeat discarded, mean of the remaining repeats. For each $k$, UnAct runs
the best configuration of its grid with that number of rounds
($^\dagger$: the selected configuration); its $\Delta$ is the five-class grid
value. SSD runs its selected configuration in the same session, so each ratio is
paired. ``Amortised'' credits SSD's importance pass over the full training set as
precomputed and reusable, which its paper allows; that pass is the listed share
of SSD's cold cost. Ratios above 1 mean UnAct is faster; bold marks the
settings where it is faster even than amortised SSD.}
\label{tab:cost}
\small
\setlength{\tabcolsep}{3.2pt}
\begin{tabular}{@{}llccccccrr@{}}
\toprule
& & & & UnAct & \multicolumn{2}{c}{SSD (s)} & full-$D$ & \multicolumn{2}{c}{UnAct speed-up} \\
\cmidrule(lr){6-7}\cmidrule(l){9-10}
Dataset & $k$ & config & $\Delta$ & (s) & amortised & cold & share (\%) & vs.\ amort. & vs.\ cold \\
\midrule
""" + "\n\\midrule\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("tab_cost.tex", body, src)
    # One-round Delta vs selected Delta (grid values).
    bk = best_per_k()
    e6 = load_e6()
    for ds in DATASETS:
        p, g, k = UNACT_SELECTED[ds]
        sel = e6[(e6.dataset == ds) & (e6.percentile == p) & (e6.gamma == g)
                 & (e6.iters == k)].score.iloc[0]
        one = bk[(bk.dataset == ds) & (bk.iters == 1)].score.iloc[0]
