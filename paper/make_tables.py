NAME = {"baseline": "Original model", "gold": "Retrain", "ssd": "SSD",
        "lfssd": "LFSSD", "unact": "UnAct (ours)"}

NUMBERS: list[tuple[str, str, str]] = []   # (macro, value, source)


def num(name, value, source, fmt="{:.2f}"):
    v = value if isinstance(value, str) else fmt.format(value)
    NUMBERS.append((name, v, source))
    return v


def write(name, body, source):
    os.makedirs(TABDIR, exist_ok=True)
    with open(os.path.join(TABDIR, name), "w", encoding="utf-8") as f:
        f.write(HEAD % source + body)
    print(f"  wrote tables/{name}")


def pm(m, s, d=2):
    return f"${m:.{d}f}${{\\scriptsize$\\,\\pm\\,{s:.{d}f}$}}"


def bold_if(v, cond, d=2):
    s = f"{v:.{d}f}"
    return f"\\textbf{{{s}}}" if cond else s


