                t = d[(d.method == meth) & (d.relearn_m == 5) & (d.step == step)
                      & d.forget_class.isin(common_cls)]
                if len(t):
                    num(f"numVitRelearnDf{M_WORD[meth]}Mfive{sw}", t.d_f.mean(), src, "{:.1f}")


