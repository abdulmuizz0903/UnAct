    num("numCoverageExceedNaive", str(int((meas > raw6.coverage_bound_pct.values + 1e-6).sum())), src)
    # cum_coverage_pct is stored to two decimals, so compare at that resolution.
    num("numCoverageExceedKmN", str(int((meas > kmn + 0.01).sum())), src)

    # --- label-free check (constant labels) --------------------------------------
    lf = pd.read_csv(os.path.join(os.path.dirname(TABDIR), "..", "results",
                                  "e9_labelfree_check.csv"))
    src = "e9_labelfree_check.csv"
    for meth in ("unact", "lfssd"):
        t = lf[lf.method == meth]
        num(f"numLabelFreeIdentical{M_WORD[meth]}", str(int(t.bit_identical.sum())), src)
        num(f"numLabelFreeDatasets{M_WORD[meth]}", str(int(t.dataset.nunique())), src)
    t = lf[lf.method == "ssd"]
    num("numLabelFreeSSDDiffMinM", t.n_params_differing.min() / 1e6, src, "{:.1f}")
    num("numLabelFreeSSDDiffMaxM", t.n_params_differing.max() / 1e6, src, "{:.1f}")

    # --- ViT relearn probe (lr 5e-4), classes complete for every method ---------
    d = load_e5c()
