def numbers_vit_forget_size():
    from common import load_e5d
    agg, raw = load_e5d()
    if agg is None:
        print("  skip ViT forget-size macros: results/e5d_vit_forget_size.csv incomplete")
        return
    src = "e5d_vit_forget_size.csv"
    for meth in ("unact", "ssd"):
        a = agg[agg.method == meth].set_index("forget_n")
        for n, w in N_WORD.items():
            if n in a.index:
                num(f"numVitFsDelta{M_WORD[meth]}N{w}", a.loc[n, "score"], src)
                num(f"numVitFsMinDr{M_WORD[meth]}N{w}", a.loc[n, "d_r_min"], src, "{:.1f}")
        full = a.index.max()
        num(f"numVitFsDelta{M_WORD[meth]}Nfull", a.loc[full, "score"], src)
        r = raw[raw.method == meth]
        num(f"numVitFsWorstDrop{M_WORD[meth]}", (r.gold_retain - r.post_retain).max(), src, "{:.1f}")

    # Wall-clock per request (one run per class; classes 0/2/3/5 on the L4, class 8
    # on the A10, both methods paired on the same card). SSD's method_time_s includes
    # its full-training-set importance pass; that pass does not depend on n, so its
    # time with the pass precomputed is t(n) - t(n=1), up to the ~1 s forget pass at n=1.
    t = raw.pivot_table(index=["forget_class", "forget_n"], columns="method",
                        values="method_time_s").reset_index()
    full = t.groupby("forget_class").forget_n.transform("max") == t.forget_n
    one = t[t.forget_n == 1].set_index("forget_class")
    tf = t[full].set_index("forget_class")
    ssd_amort = tf.ssd - one.ssd
    num("numVitFsTimeUnActFull", tf.unact.mean(), src, "{:.0f}")
    num("numVitFsTimeSSDColdFull", tf.ssd.mean(), src, "{:,.0f}")
    num("numVitFsTimeSSDAmortFull", ssd_amort.mean(), src, "{:.0f}")
    num("numVitFsTimeSSDImportance", one.ssd.mean(), src, "{:,.0f}")
    num("numVitFsSpeedupCold", (tf.ssd / tf.unact).mean(), src, "{:.0f}")
    num("numVitFsSpeedupAmort", (ssd_amort / tf.unact).mean(), src, "{:.1f}")
    num("numVitFsTimeUnActNfive", t[t.forget_n == 5].unact.mean(), src, "{:.1f}")


