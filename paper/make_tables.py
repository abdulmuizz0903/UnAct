def _main_rows():
    m = load_main()
    out = {}
    for ds in DATASETS:
        s = m[m.dataset == ds].set_index("method")
        out[ds] = s
    return out


def table_main():
    rows = _main_rows()
    src = "e2_main_table_l4.csv + e9_baselines.csv (method lfssd)"
    lines = []
    for meth in ["baseline", "gold", "ssd", "lfssd", "unact"]:
        cells = []
        for ds in DATASETS:
            s = rows[ds]
            r = s.loc[meth]
            best = s.loc[METHODS, "score"].min()
            dr, df, mia = f"{r.d_r:.2f}", f"{r.d_f:.2f}", f"{100 * r.mia:.1f}"
            if meth == "gold":
                sc = "---"
            elif meth == "baseline":
                sc = f"{r.score:.2f}"
            else:
                sc = bold_if(r.score, np.isclose(r.score, best))
            cells += [dr, df, mia, sc]
        label = NAME[meth] if meth != "unact" else "\\textbf{UnAct} (ours)"
        lines.append(f"{label} & " + " & ".join(cells) + r" \\")
        if meth == "gold":
            lines.append(r"\midrule")
    for ds in DATASETS:
        s = rows[ds]
        for meth in ["gold", "ssd", "lfssd", "unact", "baseline"]:
            r = s.loc[meth]
            w = DS_WORD[ds] + M_WORD[meth]
            num(f"numDr{w}", r.d_r, src)
            num(f"numDf{w}", r.d_f, src)
            num(f"numMIA{w}", 100 * r.mia, src, "{:.1f}")
