def _nstar(s):
    b = s.score.min()
    return int(s[s.score <= 2 * b].forget_n.min())


def table_data_efficiency():
    data = load_e3_all()
    src = "e3_forget_size.csv (unact, ssd) + e3_lfssd_forget_size.csv"
    meths = [m for m in METHODS if m in data]
    ns = sorted(set(data["unact"].forget_n))
    lines = []
    for n in ns:
        cells = []
        for ds in DATASETS:
            vals = {}
            for m in meths:
                d = data[m]
                r = d[(d.dataset == ds) & (d.forget_n == n)]
                vals[m] = r.score.iloc[0] if len(r) else None
            present = [v for v in vals.values() if v is not None]
            best = min(present) if present else None
            for m in meths:
                v = vals[m]
                cells.append("---" if v is None else bold_if(v, np.isclose(v, best)))
        lines.append(f"{n} & " + " & ".join(cells) + r" \\")
    tail = []
    for ds in DATASETS:
        for m in meths:
            d = data[m]
            s = d[d.dataset == ds]
            ns_ = _nstar(s)
            tail.append(str(ns_))
            num(f"numNstar{M_WORD[m]}{DS_WORD[ds]}", str(ns_), src)
    lines.append(r"\midrule")
    lines.append(r"$n^\star$ & " + " & ".join(tail) + r" \\")
    # Numbers quoted in the text.
    for ds in DATASETS:
        for m in meths:
            d = data[m]
            s = d[d.dataset == ds].set_index("forget_n")
            for n in (1, 5, 10, 25):
                if n in s.index:
                    num(f"numDelta{M_WORD[m]}{DS_WORD[ds]}N{ {1:'one',5:'five',10:'ten',25:'twentyfive'}[n] }".replace(" ", ""),
                        s.loc[n, "score"], src)
            num(f"numMinDr{M_WORD[m]}{DS_WORD[ds]}", s.d_r.min(), src)
    raw = load_e3_raw()
    raw["drop"] = raw.gold_retain - raw.post_retain
    worst = raw.groupby(["dataset", "method"])["drop"].max()
    for ds in DATASETS:
        for m in meths:
            num(f"numWorstDrop{M_WORD[m]}{DS_WORD[ds]}", worst.loc[(ds, m)], src)
    un = data["unact"]
    full = un.groupby("dataset").apply(lambda s: s.sort_values("forget_n").score.iloc[-1],
                                       include_groups=False)
    dev = max((un[(un.dataset == ds) & (un.forget_n >= 25)].score - full[ds]).abs().max()
              for ds in DATASETS)
    num("numUnActMaxDevFromFullNgeTwentyfive", dev, src)
    num("numUnActRunsEthree", str(int(len(raw[raw.method == "unact"]))), src)

    ncol = len(meths)
    heads = " & ".join({"ssd": "SSD", "lfssd": "LFSSD", "unact": "UnAct"}[m] for m in meths)
    cm = "".join(f"\\cmidrule(lr){{{2 + i * ncol}-{1 + (i + 1) * ncol}}}" for i in range(3))
    body = r"""\begin{table}[t]
\centering
\caption{Distance to the retrained model $\Delta$ against the number of forget
images $n$ each method is shown; the best method in each cell group is in bold.
Every method runs at its single selected configuration at every $n$. The class
being removed and the retain set are fixed, and SSD and LFSSD always receive
their importance pass over the full training set, so $n$ measures only how much
evidence a method needs to locate the class. The last $n$ of each dataset is the
whole class. $n^\star$ is the smallest $n$ at which a method comes within
$2\times$ of its own best $\Delta$.}
\label{tab:data-efficiency}
\small
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{@{}r""" + "c" * (3 * ncol) + r"""@{}}
\toprule
& \multicolumn{""" + str(ncol) + r"""}{c}{CIFAR-10} & \multicolumn{""" + str(ncol) + r"""}{c}{CIFAR-20} & \multicolumn{""" + str(ncol) + r"""}{c}{CIFAR-100} \\
""" + cm + "\n$n$ & " + " & ".join([heads] * 3) + r""" \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("tab_data_efficiency.tex", body, src)


