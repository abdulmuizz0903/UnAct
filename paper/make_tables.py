def write_numbers():
    seen = {}
    lines = []
    for name, v, src in NUMBERS:
        if name in seen:
            if seen[name] != v:
                raise ValueError(f"macro {name} defined twice with {seen[name]} and {v}")
            continue
        seen[name] = v
        lines.append(f"\\newcommand{{\\{name}}}{{{v}}}  % {src}")
    with open(os.path.join(TABDIR, "numbers.tex"), "w", encoding="utf-8") as f:
        f.write("%% Generated by paper/make_tables.py -- every number quoted in the prose.\n")
        f.write("%% \\input{tables/numbers} in the preamble, then write e.g. \\numDeltaCtenUnAct.\n")
        f.write("\n".join(lines) + "\n")
    print(f"  wrote tables/numbers.tex ({len(lines)} macros)")


